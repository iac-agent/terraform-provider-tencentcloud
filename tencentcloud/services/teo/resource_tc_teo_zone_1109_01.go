// Create handles `terraform apply` for new resources.
func (r *TeoZone110901Resource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan TeoZone110901ResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if r.Client() == nil {
		resp.Diagnostics.AddError(
			"Provider not configured",
			"The provider client is not available. This is unexpected; please report it.",
		)
		return
	}

	request := teoNewCreateZoneRequest()
	request.Type = teoStringPtrOrNull(plan.Type)
	request.ZoneName = teoStringPtrOrNull(plan.ZoneName)
	request.Area = teoStringPtrOrNull(plan.Area)
	request.PlanId = teoStringPtrOrNull(plan.PlanId)
	request.AliasZoneName = teoStringPtrOrNull(plan.AliasZoneName)
	request.AllowDuplicates = teoBoolPtrOrNull(plan.AllowDuplicates)
	request.JumpStart = teoBoolPtrOrNull(plan.JumpStart)
	if !plan.Tags.IsNull() && !plan.Tags.IsUnknown() {
		var tags []teoTagModel
		resp.Diagnostics.Append(plan.Tags.ElementsAs(ctx, &tags, false)...)
		if resp.Diagnostics.HasError() {
			return
		}
		request.Tags = teoTagsFromModels(tags)
	}

	response, err := r.Client().UseTeoClient().CreateZone(request)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error creating TEO zone",
			fmt.Sprintf("CreateZone failed: %v", err),
		)
		return
	}
	if response == nil || response.Response == nil || response.Response.ZoneId == nil || *response.Response.ZoneId == "" {
		resp.Diagnostics.AddError(
			"Error creating TEO zone",
			"CreateZone returned an empty response or an empty zone id.",
		)
		return
	}

	zoneId := *response.Response.ZoneId
	plan.Id = types.StringValue(zoneId)
	plan.ZoneId = types.StringValue(zoneId)

	// Persist the identity BEFORE any follow-up read, so a later failure keeps
	// the resource in state and `terraform destroy` can clean it up.
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Read back to align state with the cloud side. A partial failure here
	// keeps the id in state; the next refresh reconciles.
	zone, err := teoDescribeZoneById(ctx, r.Client(), zoneId)
	if err != nil {
		resp.Diagnostics.AddError(
			"Error reading TEO zone after create",
			fmt.Sprintf("DescribeZones failed for zone %s: %v", zoneId, err),
		)
		return
	}
	if zone == nil {
		resp.Diagnostics.AddError(
			"TEO zone not readable after create",
			fmt.Sprintf("zone %s was created but cannot be read back", zoneId),
		)
		return
	}
	teoZone110901RefreshModel(ctx, &plan, zone)
	teoZone110901ResolveUnknown(&plan)
	resp.Diagnostics.Append(resp.State.Set(ctx, &plan)...)
}

// Read handles `terraform refresh` and post-apply state refresh.
